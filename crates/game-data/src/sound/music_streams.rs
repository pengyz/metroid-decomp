/// 按曲号（SongHeaderOffsetTable 序）×通道（0=SQ1/1=SQ2/2=Tri/3=Noise）取流。
pub fn song_stream(song: usize, ch: usize) -> Option<&'static [u8]> {
    SONG_STREAMS.get(song).and_then(|s| s.get(ch)).copied().flatten()
}

/// 按**基址**反查流（忠实径：乐循环读 $0630+2X 基址字取流——$065E 曲号会被
/// 音乐 cycle 的 FindMusicInitIndex 重置，不可作键）。
pub fn stream_by_base(base: u16) -> Option<&'static [u8]> {
    for (song, row) in STREAM_BASES.iter().enumerate() {
        for (ch, b) in row.iter().enumerate() {
            if *b == base && base != 0 {
                return song_stream(song, ch);
            }
        }
    }
    None
}

