//! game-core::memmap::observe —— **观测面**：把内存状态导出成可对拍/可诊断的形态。
//!
//! 与 `views/` 的分工（本目录存在的理由）：
//! - `views/`：语义视图，回答「这个状态**是什么**」（`samus.status()`）——领域代码只走它；
//! - `observe/`：字节视图，回答「这个状态**长什么样**」（`zp/iram/wram` 三段 hex）——对拍与
//!   `--state-out` 只走它。
//!
//! 之所以把两者分开：对拍要的是**emu 的字节布局**，而领域代码要的是**语义**。混在一个
//! 目录里会诱导「为了取数方便而把语义写成地址」，正是本轮架构清理要消除的形态。
//! 判定权仍在像素（L4/录像），本层不参与 pass/fail——它只是显微镜。

