-- tools/scenario_capture.lua —— S2 oracle 场景采集执行器（通用）
-- 由 tools/scenario_run.py 把 PLAN 表字面量前置后整拼为 analysis/_gen/<name>.lua 喂给 Mesen2 2.1.1。
-- DSL 语义只在 tools/scenario_run.py 解析（无第二套解析逻辑）；本文件只执行 PLAN。
--
-- API 依据（Mesen2 2.1.1 实测探针，见任务 t8/t12 记录）：
--   emu.addEventCallback(fn, "inputPolled"|"endFrame")  帧回调
--   emu.setInput({a=..,b=..,start=..,select=..,up=..,down=..,left=..,right=..}, 0)  注入按键
--   emu.read(address, memType)  读一字节（memType=内存类型枚举；RAM 见 MEMTYPE）
--   emu.takeScreenshot() -> png 字节串（需自行落盘）
--   emu.getState()  全机状态（cpu.pc/a/x/y/sp、ppu.*、mapper.*、frameCount）
--   emu.stop  停止模拟但**不退出进程** ⇒ 驱动看 DONE 标记后 SIGTERM
--
-- 帧计数约定（差分复现靠它锁死）：
--   frame 在 inputPolled 递增；schedule[frame] 的按键在该帧注入；
--   endFrame（帧 N 渲染完成后）写 trace 行 / 截图 / RAM dump；frame == PLAN.frames 写 DONE 并停机。

local PLAN = PLAN or error("PLAN missing: must be generated by tools/scenario_run.py")

-- memType=8：CPU 总线视图（Mesen2 MemoryType 枚举值，t12 探针实测——mt 0..40 仅 8/9 非零；
-- B 级证据：f600 时 mt=8 读 $0002=FF、$0100 栈页=C1、$8000=A9（恰为 LDA# 操作码）、
-- RAM[0..63] 26 字节非零；mt=255 报 invalid memory type。勿凭猜测改）。
local MEMTYPE = PLAN.memtype or 8

local name = PLAN.name
local frames = PLAN.frames
local pressLen = PLAN.press_len or 2
local tracePath = PLAN.out_dir .. "/" .. name .. ".frames.jsonl"
local capPath = PLAN.out_dir .. "/" .. name .. ".captures.jsonl"
local donePath = PLAN.out_dir .. "/" .. name .. ".done"
local logPath = PLAN.out_dir .. "/" .. name .. ".lua.log"

local function log(s)
  -- 文本产物一律 "wb"/"ab" 二进制模式（2026-10-14 Windows 适配）：C 运行时文本模式会把
  -- "\n" 翻译成 "\r\n"，trace/captures 字节面随平台漂移 ⇒ oracle_sha256 锚定破裂。
  local f = io.open(logPath, "ab")
  if f then f:write(s .. "\n") f:close() end
end

local function hex2(n) return string.format("%02X", n) end

local function jstr(s)
  s = tostring(s):gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n"):gsub("\r", "\\r")
  return '"' .. s .. '"'
end

-- 帧计数与计数器：必须先于 saveShot/dumpRam 等闭包声明（Lua 词法作用域，
-- 声明在后的 local 不会被先前闭包捕获——t12 更正注）。
local frame = 0
local inputWarned = false
local nTrace, nCap, nShot = 0, 0, 0

-- ---------------- 输入计划展开为逐帧按键表
local schedule = {}
local function addRange(a, b, btns)
  for f = a, b do
    local t = schedule[f]
    if not t then t = {} schedule[f] = t end
    for _, btn in ipairs(btns) do t[btn] = true end
  end
end
for _, e in ipairs(PLAN.holds) do addRange(e.from, e.to, e.buttons) end
for _, e in ipairs(PLAN.presses) do addRange(e.frame, e.frame + pressLen - 1, e.buttons) end

-- 采集点索引
local capAt = {}
for _, e in ipairs(PLAN.captures) do capAt[e.frame] = e.tag end
local everyN = PLAN.capture_every and PLAN.capture_every.n or 0
local everyTag = PLAN.capture_every and PLAN.capture_every.tag or "auto"

-- ---------------- 内存读取
local function readByte(addr)
  local ok, v = pcall(emu.read, addr, MEMTYPE)
  if ok then return v end
  return 0
end

local function readRange(fromAddr, toAddr)
  local parts = {}
  for a = fromAddr, toAddr do parts[#parts + 1] = hex2(readByte(a)) end
  return table.concat(parts)
end

local function cpuJson()
  local st = emu.getState()
  return string.format('{"pc":%d,"a":%d,"x":%d,"y":%d,"sp":%d}',
    st["cpu.pc"], st["cpu.a"], st["cpu.x"], st["cpu.y"], st["cpu.sp"])
end

local function saveShot(tag)
  local ok, png = pcall(emu.takeScreenshot)
  if ok and type(png) == "string" then
    local p = string.format("%s/%s_f%05d_%s.png", PLAN.shots_dir, name, frame, tag)
    local f = io.open(p, "wb")
    if f then f:write(png) f:close() return p end
  end
  log("takeScreenshot failed at frame " .. frame)
  return nil
end

local function dumpRam(tag)
  local p = string.format("%s/%s_f%05d_%s.ram.hex", PLAN.out_dir, name, frame, tag)
  local f = io.open(p, "wb")
  if f then f:write(readRange(0x0000, 0x07FF) .. "\n") f:close() return p end
  return nil
end

-- ---------------- 覆盖采集（PLAN.coverage；缺口左移机制③）
-- ⚠ rounds/r2 F1（实测证伪）：字符串 "execute" 回调集合 ≠ 已执行地址集（近似总线读周期：
-- 漏记 NMI/reset 入口首指令、混入操作数字节）；Mesen2 2.1.1 无 memCallbackType 枚举表。
-- 本采集产物仅为**未验证线索**，须经 tools/coverage_from_trace.py 自校验（cpu.pc ⊆ 集合）
-- 通过后方可作盲区线索；语义根治方案待立（CDL / 逐指令 trace）。
local covSet, covN, covMode = {}, 0, "off"
if PLAN.coverage then
  local function covHit(address)
    if not covSet[address] then covSet[address] = true covN = covN + 1 end
  end
  local ok = pcall(emu.addMemoryCallback, covHit, "execute", 0x8000, 0xFFFF)
  if not ok then
    ok = pcall(emu.addMemoryCallback, covHit,
      emu.memCallbackType and emu.memCallbackType.execute or "execute", 0x8000, 0xFFFF)
  end
  covMode = ok and "execute-callback" or "unsupported"
  log("coverage mode: " .. covMode)
end

-- ---------------- r3：待查段指令入口覆盖（PLAN.coverage_pc）
-- ⚠ 语义演进（probe_dispatch_diag v4/v7 A 级实证，2026-10-15）：
--   字符串 "execute" 注册=**劣化语义**（操作数/数据读，opcode fetch 不可见——r2 F1
--   全部怪象的根因）；`emu.callbackType.exec` 枚举注册=**真 opcode fetch 回调**
--   （对照：C0BF str=0/enum=55，C0D9 str=0/enum=59——r2 F1 盲点可见）。
-- 本模式用枚举注册 ⇒ **真指令入口覆盖**（A 级执行证据）。已知余量：中断劫持首条
-- 指令（若回调在向量派发前注册时机受限——实测 C0D9 可见）。
local covPcSet, covPcN, covPcMode, covPcHits = {}, 0, "off", 0
if PLAN.coverage_pc and #PLAN.coverage_pc > 0 then
  local function covPcHit(address)
    covPcHits = covPcHits + 1
    if not covPcSet[address] then
      covPcSet[address] = true
      covPcN = covPcN + 1
    end
  end
  local allOk, mode = true, "exec-callback-enum"
  for _, r in ipairs(PLAN.coverage_pc) do
    local lo, hi = tonumber(r[1], 16), tonumber(r[2], 16)
    local ok = false
    if emu.callbackType and emu.callbackType.exec then
      ok = pcall(emu.addMemoryCallback, covPcHit, emu.callbackType.exec, lo, hi)
    end
    if not ok then  -- 回退：数字 2（枚举值）；再退字符串（劣化语义，如实标注）
      ok = pcall(emu.addMemoryCallback, covPcHit, 2, lo, hi)
      if not ok then
        ok = pcall(emu.addMemoryCallback, covPcHit, "execute", lo, hi)
        mode = "bus-access-degraded"
      end
    end
    allOk = allOk and ok
    log(string.format("coverage_pc %04X-%04X cb=%s mode=%s", lo, hi, tostring(ok), mode))
  end
  covPcMode = allOk and mode or "partial"
end

-- ---------------- r3：分发器入口探针（PLAN.probe_dispatch）
-- 注册=callbackType.exec（真 opcode fetch）；**站点签名**（ret-2..ret == 20 7C C2）
-- 作不变量自校验（不匹配者单列 tail-jmp/异常入口，不静默丢弃）。
-- site = ret-1 - 2（JSR 压返回址-1）；target = word(site+3+2*A)（C27C 静态语义）；
-- A 真值性按「同 site 多次命中 a 应有分布」不变量核。
-- 窗口指纹=$8000-$800F 16 字节（离线对各 PRG bank 自证映射——A9 假设证据面）。
local dispAgg, dispEvents, dispN, dispRaw, dispCapN = {}, {}, 0, 0, 5000
local dispMode = "off"
if PLAN.probe_dispatch and #PLAN.probe_dispatch > 0 then
  local function dspHit(address)
    dispRaw = dispRaw + 1
    local ok, st = pcall(emu.getState)
    if not ok or not st then return end
    local sp = st["cpu.sp"] or (st.cpu and st.cpu.sp)
    if not sp then return end
    local plo = readByte(0x0100 + ((sp + 1) % 256))
    local phi = readByte(0x0100 + ((sp + 2) % 256))
    local ret = plo + phi * 256
    local site = ret - 2
    local sig = (readByte(site) == 0x20 and readByte(site + 1) == 0x7C
      and readByte(site + 2) == 0xC2)
    local a = st["cpu.a"] or (st.cpu and st.cpu.a) or 0
    local taddr = site + 3 + 2 * a
    local tgt = readByte(taddr) + readByte(taddr + 1) * 256
    local win = readRange(0x8000, 0x800F)
    dispN = dispN + 1
    local key = string.format("%s|%04X|%d|%04X", sig and "jsr" or "other", site, a, tgt)
    local agg = dispAgg[key]
    if not agg then
      agg = { n = 0, first = frame, last = frame, wins = {} }
      dispAgg[key] = agg
    end
    agg.n = agg.n + 1
    agg.last = frame
    agg.wins[win] = true
    if dispN <= dispCapN then
      dispEvents[#dispEvents + 1] = string.format(
        '{"f":%d,"sig":"%s","site":"%04X","a":%d,"tgt":"%04X","win":"%s"}',
        frame, sig and "jsr" or "other", site, a, tgt, win)
    end
  end
  local allOk, mode = true, "exec-callback-enum"
  for _, ad in ipairs(PLAN.probe_dispatch) do
    local addr = tonumber(ad, 16)
    local ok = false
    if emu.callbackType and emu.callbackType.exec then
      ok = pcall(emu.addMemoryCallback, dspHit, emu.callbackType.exec, addr, addr)
    end
    if not ok then
      ok = pcall(emu.addMemoryCallback, dspHit, 2, addr, addr)
      if not ok then
        ok = pcall(emu.addMemoryCallback, dspHit, "execute", addr, addr)
        mode = "bus-access-degraded"
      end
    end
    allOk = allOk and ok
    log(string.format("probe_dispatch %04X cb=%s mode=%s", addr, tostring(ok), mode))
  end
  dispMode = allOk and mode or "partial"
end

-- ---------------- task-12：执行路径入口探针（PLAN.entry_probe，callbackType.exec）
-- 每地址一个回调（真 opcode fetch 语义）；聚合执行序（全局 seq）+ 调用者边
-- （栈 ret-2 反推 site；site 首字节 0x20=JSR 边，否则 kind=other——顺流/JMP 入口）。
-- 产物：<name>.entries.jsonl（每入口一行）+ <name>.edges.jsonl（调用边聚合）。
local epStats, epEdges, epHits, epSeq = {}, {}, 0, 0
local epMode = "off"
local nmiLog, nmiN = {}, 0   -- task-15：C0D9 帧界时间线（scanline/vblank 相位）
if PLAN.entry_probe and #PLAN.entry_probe > 0 then
  local function epHit(address)
    epHits = epHits + 1
    epSeq = epSeq + 1
    local ok, st = pcall(emu.getState)
    if not ok or not st then return end
    local sp = st["cpu.sp"] or (st.cpu and st.cpu.sp)
    local scan = st["ppu.scanline"] or (st.ppu and st.ppu.scanline) or -1
    local vb = st["ppu.statusFlags.verticalBlank"]
    if vb == nil and st.ppu and st.ppu.statusFlags then
      vb = st.ppu.statusFlags.verticalBlank
    end
    local caller, kind = "none", "other"
    if sp then
      local plo = readByte(0x0100 + ((sp + 1) % 256))
      local phi = readByte(0x0100 + ((sp + 2) % 256))
      local site = (plo + phi * 256) - 2
      caller = string.format("%04X", site)
      if readByte(site) == 0x20 then kind = "jsr" end
    end
    local s = epStats[address]
    if not s then
      s = { n = 0, first_seq = epSeq, first_frame = frame, last_frame = frame,
            first_scanline = scan, first_vblank = vb, first_sp = sp }
      epStats[address] = s
    end
    s.n = s.n + 1
    s.last_frame = frame
    if address == 0xC0D9 and nmiN < 4000 then
      nmiN = nmiN + 1
      nmiLog[#nmiLog + 1] = string.format(
        '{"f":%d,"seq":%d,"scanline":%d,"vblank":%s,"sp":%s,"caller":"%s"}',
        frame, epSeq, scan, tostring(vb), tostring(sp), caller)
    end
    local ek = caller .. "|" .. string.format("%04X", address) .. "|" .. kind
    local e = epEdges[ek]
    if not e then
      e = { n = 0, first_seq = epSeq }
      epEdges[ek] = e
    end
    e.n = e.n + 1
  end
  local allOk, mode = true, "exec-callback-enum"
  for _, ad in ipairs(PLAN.entry_probe) do
    local addr = tonumber(ad, 16)
    local ok = false
    if emu.callbackType and emu.callbackType.exec then
      ok = pcall(emu.addMemoryCallback, epHit, emu.callbackType.exec, addr, addr)
    end
    if not ok then
      ok = pcall(emu.addMemoryCallback, epHit, 2, addr, addr)
      if not ok then
        ok = pcall(emu.addMemoryCallback, epHit, "execute", addr, addr)
        mode = "bus-access-degraded"
      end
    end
    if not ok then allOk = false end
  end
  epMode = allOk and mode or "partial"
  log(string.format("entry_probe %d 个地址 cb mode=%s", #PLAN.entry_probe, epMode))
end

-- ---------------- r3：$8000 窗口指纹时间线（A9 证据面：每帧 16 字节自证映射）
local winF = nil
if (PLAN.probe_dispatch and #PLAN.probe_dispatch > 0)
    or (PLAN.entry_probe and #PLAN.entry_probe > 0) then
  winF = io.open(PLAN.out_dir .. "/" .. name .. ".window.jsonl", "wb")
end

-- ---------------- 回调注册
local traceF = assert(io.open(tracePath, "wb"))
local capF = assert(io.open(capPath, "wb"))

-- W-NEW 行缓冲 NMI 级插桩（t94）：probe_mem 写点 PC 轨迹（观察性，不改行为）
if PLAN.probe_mem and #PLAN.probe_mem > 0 then
  local probePath = PLAN.out_dir .. "/" .. name .. ".probe.jsonl"
  local probeF = io.open(probePath, "wb")
  local probeN = 0
  local function probeLog(addr, val)
    if probeN > 3000000 then return end
    probeN = probeN + 1
    local ok, st = pcall(emu.getState)
    -- ⚠ pc 字段=回调地址回显（r3 v1 实证，非写者 PC）——写者归属用 caller（栈 ret-2
    -- 反推 site，首字节 0x20=JSR 语境）；task-15 ③ 栈页残迹机理靠 caller/sp/scanline。
    local pc = (ok and st and st.cpu) and string.format("%04X", st.cpu.pc or 0) or "????"
    local fc = (ok and st) and (st.frameCount or 0) or 0
    local sp = (ok and st) and st["cpu.sp"] or nil
    local scan = (ok and st) and st["ppu.scanline"] or -1
    local caller, kind = "none", "other"
    if sp then
      local plo = readByte(0x0100 + ((sp + 1) % 256))
      local phi = readByte(0x0100 + ((sp + 2) % 256))
      local site = (plo + phi * 256) - 2
      caller = string.format("%04X", site)
      if readByte(site) == 0x20 then kind = "jsr" end
    end
    probeF:write(string.format(
      '{"f":%d,"pc":"%s","a":"%04X","v":%d,"caller":"%s","kind":"%s","sp":%s,"scanline":%d}\n',
      fc, pc, addr, val, caller, kind, tostring(sp), scan))
    if probeN % 512 == 0 then probeF:flush() end
  end
  for _, r in ipairs(PLAN.probe_mem) do
    local lo, hi = tonumber(r[1], 16), tonumber(r[2], 16)
    -- r3 同族教训（task-15 实测）：字符串 "write" 注册=读写不分的劣化语义
    -- （$1A 轮询读混入 1.37M/1.38M）——枚举 callbackType.write 才是真写点。
    local wmode = "callbackType.write"
    local ok = false
    if emu.callbackType and emu.callbackType.write then
      ok = pcall(emu.addMemoryCallback, function(address, value)
        probeLog(address, value)
      end, emu.callbackType.write, lo, hi)
    end
    if not ok then
      ok = pcall(emu.addMemoryCallback, function(address, value)
        probeLog(address, value)
      end, 1, lo, hi)
      wmode = "numeric-1"
    end
    if not ok then
      ok = pcall(emu.addMemoryCallback, function(address, value)
        probeLog(address, value)
      end, "write", lo, hi)
      wmode = "bus-access-degraded"
    end
    probeF:write(string.format('{"probe":"%04X-%04X","cb":%s,"mode":"%s"}\n',
      lo, hi, tostring(ok), wmode))
    probeF:flush()
  end
  emu.addEventCallback(function() probeF:flush() end, "endFrame")
end

emu.addEventCallback(function()
  frame = frame + 1
  local btn = schedule[frame] or {}
  local okIn, errIn = pcall(emu.setInput, btn, 0)
  if not okIn and not inputWarned then
    inputWarned = true
    log("setInput FAILED: " .. tostring(errIn))
  end
end, "inputPolled")

emu.addEventCallback(function()
  if frame < 1 or frame > frames then return end

  -- 逐帧状态向量
  local wparts = {}
  for _, w in ipairs(PLAN.watch) do
    wparts[#wparts + 1] = jstr(w.label) .. ":" .. readByte(tonumber(w.addr, 16))
  end
  for _, r in ipairs(PLAN.watch_ranges) do
    wparts[#wparts + 1] = jstr(r.label) .. ':"' .. readRange(tonumber(r.from, 16), tonumber(r.to, 16)) .. '"'
  end
  local line = '{"f":' .. frame .. ',"w":{' .. table.concat(wparts, ",") .. "}"
  if PLAN.ramframe then
    line = line .. ',"ram":"' .. readRange(0x0000, 0x07FF) .. '"'
  end
  traceF:write(line .. "}\n")
  nTrace = nTrace + 1

  -- 采集点（显式 tag 或 capture_every）
  local tag = capAt[frame]
  if not tag and everyN > 0 and frame % everyN == 0 then tag = everyTag end
  if tag then
    local shot = saveShot(tag)
    local ram = dumpRam(tag)
    capF:write(string.format('{"f":%d,"tag":%s,"shot":%s,"ram":%s,"cpu":%s}\n',
      frame, jstr(tag), shot and jstr(shot) or "null", ram and jstr(ram) or "null", cpuJson()))
    nCap = nCap + 1
    nShot = nShot + (shot and 1 or 0)
    capF:flush()
  end

  if frame % 120 == 0 then traceF:flush() end

  -- r3：$8000 窗口指纹时间线（每帧一行；A9 证据面）
  if winF then
    winF:write(string.format('{"f":%d,"win":"%s"}\n', frame, readRange(0x8000, 0x800F)))
  end

  if frame == frames then
    traceF:flush() traceF:close()
    capF:flush() capF:close()
    if winF then winF:flush() winF:close() end
    if PLAN.coverage then
      local covPath = PLAN.out_dir .. "/" .. name .. ".coverage.jsonl"
      local covF = io.open(covPath, "wb")
      if covF then
        local addrs = {}
        for a, _ in pairs(covSet) do addrs[#addrs + 1] = a end
        table.sort(addrs)
        covF:write(string.format('{"mode":"%s","count":%d,"range":"8000-FFFF"}\n', covMode, covN))
        for _, a in ipairs(addrs) do
          covF:write(string.format('{"a":"%04X"}\n', a))
        end
        covF:close()
        log("coverage dumped: " .. covN .. " addrs, mode=" .. covMode)
      end
    end
    -- r3：pc 过滤指令入口覆盖
    if PLAN.coverage_pc and #PLAN.coverage_pc > 0 then
      local p = PLAN.out_dir .. "/" .. name .. ".exec_cov.jsonl"
      local f = io.open(p, "wb")
      if f then
        local addrs = {}
        for a, _ in pairs(covPcSet) do addrs[#addrs + 1] = a end
        table.sort(addrs)
        f:write(string.format('{"mode":"%s","count":%d,"hits":%d,"blind":"interrupt-entry-first-opcodes"}\n',
          covPcMode, covPcN, covPcHits))
        for _, a in ipairs(addrs) do
          f:write(string.format('{"a":"%04X"}\n', a))
        end
        f:close()
        log("exec_cov dumped: " .. covPcN .. " addrs, mode=" .. covPcMode)
      end
    end
    -- r3：分发探针事件 + 聚合（(site,a,tgt) 为键；wins=$8000 窗口指纹集）
    if PLAN.probe_dispatch and #PLAN.probe_dispatch > 0 then
      local ef = io.open(PLAN.out_dir .. "/" .. name .. ".dispatch.jsonl", "wb")
      if ef then
        ef:write(string.format('{"mode":"%s","events":%d,"total":%d,"raw_hits":%d}\n',
          dispMode, #dispEvents, dispN, dispRaw))
        for _, l in ipairs(dispEvents) do ef:write(l .. "\n") end
        ef:close()
      end
      local sf = io.open(PLAN.out_dir .. "/" .. name .. ".dispatch_summary.jsonl", "wb")
      if sf then
        local keys = {}
        for k, _ in pairs(dispAgg) do keys[#keys + 1] = k end
        table.sort(keys)
        for _, k in ipairs(keys) do
          local agg = dispAgg[k]
          local wins = {}
          for w, _ in pairs(agg.wins) do wins[#wins + 1] = w end
          table.sort(wins)
          local sig, site, a, tgt = k:match("^(%a+)|(%x+)|(%d+)|(%x+)$")
          sf:write(string.format(
            '{"sig":"%s","site":"%s","a":%s,"tgt":"%s","n":%d,"first":%d,"last":%d,"wins":[%s]}\n',
            sig, site, a, tgt, agg.n, agg.first, agg.last,
            table.concat((function()
              local q = {}
              for _, w in ipairs(wins) do q[#q + 1] = jstr(w) end
              return q
            end)(), ",")))
        end
        sf:close()
        log("dispatch summary dumped: " .. #keys .. " triples, total " .. dispN)
      end
    end
    -- task-12：入口执行序 + 调用边
    if PLAN.entry_probe and #PLAN.entry_probe > 0 then
      local ef = io.open(PLAN.out_dir .. "/" .. name .. ".entries.jsonl", "wb")
      if ef then
        ef:write(string.format('{"mode":"%s","addrs":%d,"hits":%d}\n',
          epMode, #PLAN.entry_probe, epHits))
        local keys = {}
        for a, _ in pairs(epStats) do keys[#keys + 1] = a end
        table.sort(keys)
        for _, a in ipairs(keys) do
          local s = epStats[a]
          ef:write(string.format('{"a":"%04X","n":%d,"first_seq":%d,"first_frame":%d,"last_frame":%d,"first_scanline":%d,"first_vblank":%s,"first_sp":%s}\n',
            a, s.n, s.first_seq, s.first_frame, s.last_frame,
            s.first_scanline or -1, tostring(s.first_vblank), tostring(s.first_sp)))
        end
        ef:close()
      end
      local gf = io.open(PLAN.out_dir .. "/" .. name .. ".edges.jsonl", "wb")
      if gf then
        local keys = {}
        for k, _ in pairs(epEdges) do keys[#keys + 1] = k end
        table.sort(keys)
        for _, k in ipairs(keys) do
          local e = epEdges[k]
          local caller, callee, kind = k:match("^(%x+)|(%x+)|(%a+)$")
          gf:write(string.format('{"caller":"%s","callee":"%s","kind":"%s","n":%d,"first_seq":%d}\n',
            caller, callee, kind, e.n, e.first_seq))
        end
        gf:close()
        log("entries dumped: " .. #keys .. " edges, " .. epHits .. " hits")
      end
      -- task-15：C0D9 帧界时间线（scanline/vblank 相位证据）
      if #nmiLog > 0 then
        local nf = io.open(PLAN.out_dir .. "/" .. name .. ".nmi.jsonl", "wb")
        if nf then
          nf:write(string.format('{"root":"C0D9","hits":%d}\n', #nmiLog))
          for _, l in ipairs(nmiLog) do nf:write(l .. "\n") end
          nf:close()
          log("nmi timeline dumped: " .. #nmiLog)
        end
      end
    end
    local d = io.open(donePath, "wb")
    if d then
      d:write(string.format('{"frames":%d,"trace_lines":%d,"captures":%d,"shots":%d}\n',
        frames, nTrace, nCap, nShot))
      d:close()
    end
    log("scenario done at frame " .. frame)
    pcall(emu.stop)
  end
end, "endFrame")

